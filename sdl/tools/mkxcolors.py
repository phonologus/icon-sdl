#!/usr/bin/env python3
"""Generate src/sdl/xcolors.c, X's colour-name database, from X.Org's
rgb.txt (sdl/tools/rgb.txt, from the test VM's x11-common package) and
its licence (sdl/tools/rgb-COPYING).

    python3 sdl/tools/mkxcolors.py > src/sdl/xcolors.c
"""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
entries, seen = [], set()
for line in open(os.path.join(here, "rgb.txt")):
    if line.startswith("!") or not line.strip():
        continue
    r, g, b, name = line.split(None, 3)
    name = name.strip()
    key = name.lower()
    if key in seen:                      # first definition wins
        continue
    seen.add(key)
    entries.append((key, int(r), int(g), int(b)))
entries.sort(key=lambda e: e[0].encode())
lic = open(os.path.join(here, "rgb-COPYING")).read().rstrip()

out = sys.stdout
out.write("/*\n * xcolors.c -- X's colour names, for nativecolor(): GENERATED by\n"
          " * sdl/tools/mkxcolors.py from X.Org's rgb.txt; do not edit.\n *\n"
          " * The colour names and values are X.Org's (app/rgb), under this licence:\n *\n")
for l in lic.splitlines():
    out.write((" * " + l).rstrip() + "\n")
out.write(" */\n#include <string.h>\n#include <strings.h>\n#include \"sdlgfx.h\"\n\n")
out.write("static const struct { const char *name; unsigned char r, g, b; } xc[] = {\n")
for k, r, g, b in entries:
    out.write('   {"%s", %d, %d, %d},\n' % (k, r, g, b))
out.write("};\n\n")
out.write('''/* Look up an X colour name (case-insensitively, as the X server does);
 * returns 1 and the 8-bit device values, or 0. */
int xcolor_lookup(const char *name, int *r, int *g, int *b)
{
   int lo = 0, hi = (int)(sizeof xc / sizeof xc[0]) - 1;
   while (lo <= hi) {
      int mid = (lo + hi) / 2, c = strcasecmp(name, xc[mid].name);
      if (c == 0) {
         *r = xc[mid].r; *g = xc[mid].g; *b = xc[mid].b;
         return 1;
      }
      if (c < 0) hi = mid - 1; else lo = mid + 1;
   }
   return 0;
}
''')
